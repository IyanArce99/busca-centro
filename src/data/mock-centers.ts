import type { Center, CenterOwnership, CenterService, CenterType } from "@/types/center";

function buildFaqs(centerName: string) {
  return [
    {
      question: `¿Cómo puedo solicitar información sobre ${centerName}?`,
      answer: `Puedes usar el formulario de esta ficha para solicitar información directamente a ${centerName}. El centro recibirá tu consulta y podrá responderte por teléfono o email.`,
    },
    {
      question: `¿Los datos de ${centerName} están verificados?`,
      answer: `Parte de la información de ${centerName} puede proceder de fuentes públicas o de datos facilitados por el propio centro. Si formas parte del equipo, puedes reclamar esta ficha para confirmar o actualizar los datos.`,
    },
  ];
}

/** Spreads mock "last updated" dates across the past ~2 months so recency sorting feels real. */
const UPDATED_AT_BASE = new Date("2026-06-28T09:00:00.000Z").getTime();
function buildUpdatedAt(index: number): string {
  const daysAgo = (index * 17) % 60;
  return new Date(UPDATED_AT_BASE - daysAgo * 24 * 60 * 60 * 1000).toISOString();
}

interface CenterSeed {
  slug: string;
  name: string;
  type: CenterType;
  ownership: CenterOwnership;
  citySlug: string;
  cityName: string;
  neighborhood?: string;
  street: string;
  postalCode: string;
  services: CenterService[];
  ageMinMonths: number;
  ageMaxMonths: number;
  schedule?: string;
  shortDescription: string;
  longDescription?: string;
  isClaimed?: boolean;
  isVerified?: boolean;
  withContact?: boolean;
}

function buildCenter(seed: CenterSeed, index: number): Center {
  const id = `center-${String(index + 1).padStart(3, "0")}`;
  const withContact = seed.withContact ?? true;

  return {
    id,
    slug: seed.slug,
    name: seed.name,
    type: seed.type,
    ownership: seed.ownership,
    address: {
      street: seed.street,
      postalCode: seed.postalCode,
      citySlug: seed.citySlug,
      cityName: seed.cityName,
      neighborhood: seed.neighborhood,
    },
    contact: withContact
      ? {
          phone: `91${String(100000 + index * 137).slice(0, 7)}`,
          email: `info@${seed.slug.replace(/-/g, "")}.es`,
          website: `https://www.${seed.slug.replace(/-/g, "")}.es`,
        }
      : {},
    ageRange: { minMonths: seed.ageMinMonths, maxMonths: seed.ageMaxMonths },
    schedule: seed.schedule ?? "Lunes a viernes, 7:30 - 17:00",
    services: seed.services,
    shortDescription: seed.shortDescription,
    longDescription: seed.longDescription,
    faqs: buildFaqs(seed.name),
    isClaimed: seed.isClaimed ?? false,
    isVerified: seed.isVerified ?? false,
    createdAt: "2025-09-01T08:00:00.000Z",
    updatedAt: buildUpdatedAt(index),
  };
}

